/* Sound: a tiny Web Audio layer with no decoding step and no files.
   - Samples come from js/data/sounds.js (generated by tools/make_sounds.py as base64 PCM) and are
     fetched lazily the first time sound is switched on, so sound-off readers download nothing.
   - Visuals drive "voices" (looping buffers) every frame from their own simulation state, e.g. the
     wind tunnel maps fan rpm → hum pitch/level and airflow → wind level/brightness. A voice that stops
     being driven (visual paused, offscreen, or errored) fades out by itself.
   - Off by default; the header button is the user gesture that unlocks the AudioContext. */
;(function (S) {
  'use strict';
  var doc = document;
  var AC = window.AudioContext || window.webkitAudioContext;
  var ctx = null, master = null, buffers = {}, voices = [], loading = false, loaded = false;
  var STALE = 0.25;            // seconds without a set() before a voice fades out
  var RAMP = 0.08;             // smoothing time constant for level/pitch changes

  function now() { return ctx ? ctx.currentTime : 0; }

  function decode(entry) {
    var raw = atob(entry.pcm), n = raw.length >> 1;
    var buf = ctx.createBuffer(1, n, entry.sr), ch = buf.getChannelData(0);
    for (var i = 0; i < n; i++) {
      var lo = raw.charCodeAt(2 * i), hi = raw.charCodeAt(2 * i + 1);
      var v = (hi << 8) | lo; if (v & 0x8000) v -= 0x10000;
      ch[i] = v / 32768;
    }
    return buf;
  }

  function ensureContext() {
    if (ctx || !AC) return !!ctx;
    try { ctx = new AC({ latencyHint: 'interactive' }); } catch (e) { try { ctx = new AC(); } catch (e2) { return false; } }
    master = ctx.createGain(); master.gain.value = 0;
    master.connect(ctx.destination);
    return true;
  }

  function loadSounds() {
    if (loaded || loading) return;
    if (S.data.sounds) { A._onSoundsLoaded(); return; }
    loading = true;
    var s = doc.createElement('script'); s.src = 'js/data/sounds.js'; s.async = true;
    s.onerror = function () { loading = false; console.error('sounds.js failed to load'); };
    doc.head.appendChild(s);
  }

  function attach(v) { // give a voice its live nodes
    var b = buffers[v.name]; if (!b || v.src) return;
    v.src = ctx.createBufferSource(); v.src.buffer = b; v.src.loop = true;
    v.filter = ctx.createBiquadFilter(); v.filter.type = 'lowpass'; v.filter.frequency.value = v.lp; v.filter.Q.value = 0.4;
    v.gain = ctx.createGain(); v.gain.gain.value = 0;
    v.src.playbackRate.value = v.rate;
    v.src.connect(v.filter); v.filter.connect(v.gain); v.gain.connect(master);
    v.src.start(0, (v.name.length * 0.37) % b.duration); // scatter start phases so two hums don't flange
  }
  function detach(v) {
    if (!v.src) return;
    try { v.src.stop(); } catch (e) { /* already stopped */ }
    v.src.disconnect(); v.filter.disconnect(); v.gain.disconnect();
    v.src = v.filter = v.gain = null;
  }
  function apply(v) {
    if (!v.src) return;
    var t = now(), g = v.live ? v.level * v.base : 0;
    v.gain.gain.setTargetAtTime(g, t, RAMP);
    v.src.playbackRate.setTargetAtTime(v.rate, t, RAMP);
    v.filter.frequency.setTargetAtTime(v.lp, t, RAMP * 2);
  }

  function tick() {
    if (!A.enabled || !ctx) return false;
    var t = performance.now() / 1000;
    for (var i = 0; i < voices.length; i++) {
      var v = voices[i], live = t - v.last < STALE;
      if (live !== v.live) { v.live = live; apply(v); }
    }
    return true;
  }

  var A = S.audio = {
    enabled: false,
    supported: !!AC,
    /** header toggle: on must be called from a user gesture the first time */
    setEnabled: function (on) {
      on = !!on && A.supported;
      A.enabled = on;
      S.storage.set('sound', on);
      if (on) {
        if (!ensureContext()) { A.enabled = false; return; }
        if (ctx.state === 'suspended') ctx.resume();
        loadSounds();
        master.gain.setTargetAtTime(doc.hidden ? 0 : 1, now(), 0.05);
        voices.forEach(function (v) { attach(v); apply(v); });
        S.everyFrame(tick);
      } else if (ctx) {
        master.gain.setTargetAtTime(0, now(), 0.05);
        setTimeout(function () { if (!A.enabled) { voices.forEach(detach); if (ctx.state === 'running') ctx.suspend(); } }, 300);
      }
      S.emit('sound', on);
    },
    _onSoundsLoaded: function () {
      loading = false; loaded = true;
      if (!ctx) return;
      Object.keys(S.data.sounds).forEach(function (k) { buffers[k] = decode(S.data.sounds[k]); });
      if (A.enabled) voices.forEach(function (v) { attach(v); apply(v); });
    },
    /** A looping voice. Call voice.set({level, rate, lp}) every frame you want it audible; stop calling and it fades. */
    voice: function (name, base) {
      var v = { name: name, base: base == null ? 1 : base, level: 0, rate: 1, lp: 20000, live: false, last: -1e9, src: null };
      v.set = function (o) {
        if (o.level != null) v.level = o.level;
        if (o.rate != null) v.rate = o.rate;
        if (o.lp != null) v.lp = o.lp;
        v.last = performance.now() / 1000;
        if (!A.enabled) return;
        if (!v.src) attach(v);
        if (!v.live) { v.live = true; }
        apply(v);
      };
      voices.push(v);
      if (A.enabled && ctx) attach(v);
      return v;
    },
    /** One-shot effect. opts: {level, rate} */
    play: function (name, opts) {
      if (!A.enabled || !ctx || !buffers[name]) return;
      opts = opts || {};
      var src = ctx.createBufferSource(), g = ctx.createGain();
      src.buffer = buffers[name]; src.playbackRate.value = opts.rate || 1;
      g.gain.value = opts.level == null ? 1 : opts.level;
      src.connect(g); g.connect(master);
      src.onended = function () { src.disconnect(); g.disconnect(); };
      src.start();
    }
  };

  doc.addEventListener('visibilitychange', function () {
    if (!ctx || !A.enabled) return;
    master.gain.setTargetAtTime(doc.hidden ? 0 : 1, now(), 0.05);
  });
  // Restore the preference; actual audio starts on the first click anywhere (autoplay policy).
  if (S.storage.get('sound', false) && A.supported) {
    var unlock = function () { doc.removeEventListener('pointerdown', unlock); doc.removeEventListener('keydown', unlock); A.setEnabled(true); };
    A.enabled = true; // so the header button renders pressed before the first gesture
    doc.addEventListener('pointerdown', unlock); doc.addEventListener('keydown', unlock);
  }
})(window.SRV);
